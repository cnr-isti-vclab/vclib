template<FaceMeshConcept MeshType, FaceConcept FaceType>
void writePlyFaceIndices(
    std::ostream&                           file,
    PlyProperty                             p,
    const MeshType&                         m,
    const std::vector<IndexType<MeshType>>& vIndices,
    const FaceType&                         f,
    FileType                                format)
{
    IndexType<MeshType> fsize = f.vertexCount();
    io::writeProperty(file, fsize, p.listSizeType, format);
    for (auto vi : f.vertexIndices()) {
        io::writeProperty(file, vIndices[vi], p.type, format);
    }
}

template<FaceMeshConcept MeshType, FaceConcept FaceType>
void setPlyFaceIndices(
    FaceType&                               f,
    MeshType&                               m,
    const std::vector<IndexType<MeshType>>& vids)
{
    bool splitFace = false;
    // we have a polygonal mesh
    if constexpr (FaceType::VERTEX_COUNT < 0) {
        // need to resize the face to the right number of verts
        f.resizeVertices(vids.size());
    }
    else if (FaceType::VERTEX_COUNT != vids.size()) {
        // we have faces with static sizes (triangles), but we are loading faces
        // with number of verts > 3. Need to split the face we are loading in n
        // faces!
        splitFace = true;
    }

    if (!splitFace) { // classic load, no split needed
        uint i = 0;
        for (uint i = 0; i < f.vertexCount(); ++i) {
            if (vids[i] >= m.vertexCount()) {
                throw MalformedFileException(
                    "Bad vertex index for face " + std::to_string(f.index()));
            }
            f.setVertex(i, vids[i]);
        }
    }
    else { // split needed
        addTriangleFacesFromPolygon(m, f, vids);
    }
}

template<FaceMeshConcept MeshType, FaceConcept FaceType, typename Scalar>
void setPlyFaceWedgeTexCoords(
    FaceType&                                     f,
    MeshType&                                     m,
    const std::vector<IndexType<MeshType>>&       vids,
    const std::vector<std::pair<Scalar, Scalar>>& wedges)
{
    bool splitFace = false;
    if (FaceType::VERTEX_COUNT > 0 && FaceType::VERTEX_COUNT != wedges.size())
        splitFace = true;
    if (!splitFace) {
        for (uint i = 0; i < wedges.size(); ++i) {
            f.wedge(i).texCoord().u() = wedges[i].first;
            f.wedge(i).texCoord().v() = wedges[i].second;
        }
    }
    else { // the face has been splitted
        // for each triangle generated by the polygon
        for (uint ff = f.index(); ff < m.faceCount(); ++ff) {
            // for each vertex/wedge of the triangle
            for (uint i = 0; i < m.face(ff).vertexCount(); ++i) {
                // get the position of this vertex in the original polygon
                uint vid = m.face(ff).vertexIndex(i);
                auto it  = std::find(vids.begin(), vids.end(), vid);
                if (it == vids.end()) { // should never happen
                    // if this happens, it means that this triangle was not
                    // generated by the polygon
                    throw MalformedFileException(
                        "Bad vertex index for face " + std::to_string(ff));
                }
                // p is the position of the vertex in the polygon
                uint p                             = it - vids.begin();
                m.face(ff).wedge(i).texCoord().u() = wedges[p].first;
                m.face(ff).wedge(i).texCoord().v() = wedges[p].second;
            }
        }
    }
}

template<FaceMeshConcept MeshType, FaceConcept FaceType, typename Stream>
void readPlyFaceProperty(
    Stream&                           file,
    MeshType&                         mesh,
    FaceType&                         f,
    PlyProperty                       p,
    std::vector<IndexType<MeshType>>& vids,
    MeshInfo&                         loadedInfo,
    bool                              vcgGenerated = false,
    std::endian                       end          = std::endian::little)
{
    using IndexType  = IndexType<MeshType>;
    bool hasBeenRead = false;
    if (p.name == ply::vertex_indices) { // loading vertex indices
        uint fSize = io::readPrimitiveType<uint>(file, p.listSizeType, end);
        loadedInfo.updateMeshType(fSize);
        vids.resize(fSize);
        for (uint i = 0; i < fSize; ++i) {
            vids[i] = io::readPrimitiveType<IndexType>(file, p.type, end);
        }
        hasBeenRead = true;
        // will manage the case of loading a polygon in a triangle mesh
        setPlyFaceIndices(f, mesh, vids);
    }
    else if (p.name == ply::bit_flags) { // loading the flags of the face
        if (vcgGenerated) {
            int fval = io::readPrimitiveType<int>(file, p.type, end);
            f.importFlagsFromVCGFormat(fval);
            hasBeenRead = true;
        }
        else {
            using FlagsType = FaceType::FlagsType;
            FlagsType fval =
                io::readPrimitiveType<FlagsType>(file, p.type, end);
            f.setUnderlyingBitFlags(fval);
            hasBeenRead = true;
        }
    }
    else if (p.name == ply::texcoord) { // loading wedge texcoords
        if constexpr (HasFaceWedgeTexCoords<MeshType>) {
            if (mesh.isFaceWedgeTexCoordsAvailable()) {
                using Scalar = TexCoordType<WedgeType<FaceType>>::ScalarType;
                uint uvSize =
                    io::readPrimitiveType<uint>(file, p.listSizeType, end);
                uint                                   fSize = uvSize / 2;
                std::vector<std::pair<Scalar, Scalar>> wedges(fSize);
                for (uint i = 0; i < fSize; ++i) {
                    Scalar u = io::readPrimitiveType<Scalar>(file, p.type, end);
                    Scalar v = io::readPrimitiveType<Scalar>(file, p.type, end);
                    wedges[i].first  = u;
                    wedges[i].second = v;
                }
                hasBeenRead = true;
                setPlyFaceWedgeTexCoords(f, mesh, vids, wedges);
            }
        }
    }
    // loading material index associated to ALL the wedges
    else if (p.name == ply::material_index) {
        if constexpr (HasFaceMaterialIndex<MeshType>) {
            if (mesh.isFaceMaterialIndexAvailable()) {
                ushort n    = io::readPrimitiveType<ushort>(file, p.type, end);
                hasBeenRead = true;
                // in case the loaded polygon has been triangulated in the last
                // n triangles of mesh
                for (uint ff = f.index(); ff < mesh.faceCount(); ++ff) {
                    mesh.face(ff).materialIndex() = n;
                }
            }
        }
    }
    // loading one of the normal components
    else if (p.name >= ply::nx && p.name <= ply::nz) {
        if constexpr (HasFaceNormal<MeshType>) {
            if (mesh.isFaceNormalAvailable()) {
                using Scalar = FaceType::NormalType::ScalarType;
                int    a     = p.name - ply::nx;
                Scalar n     = io::readPrimitiveType<Scalar>(file, p.type, end);
                hasBeenRead  = true;
                // in case the loaded polygon has been triangulated in the last
                // n triangles of mesh
                for (uint ff = f.index(); ff < mesh.faceCount(); ++ff) {
                    mesh.face(ff).normal()[a] = n;
                }
            }
        }
    }
    // loading one of the color components
    else if (p.name >= ply::red && p.name <= ply::alpha) {
        if constexpr (HasFaceColor<MeshType>) {
            if (mesh.isFaceColorAvailable()) {
                int           a = p.name - ply::red;
                unsigned char c =
                    io::readPrimitiveType<unsigned char>(file, p.type, end);
                hasBeenRead = true;
                // in case the loaded polygon has been triangulated in the last
                // n triangles of mesh
                for (uint ff = f.index(); ff < mesh.faceCount(); ++ff) {
                    mesh.face(ff).color()[a] = c;
                }
            }
        }
    }
    else if (p.name == ply::quality) { // loading the quality component
        if constexpr (HasFaceQuality<MeshType>) {
            using QualityType = FaceType::QualityType;
            if (mesh.isFaceQualityAvailable()) {
                QualityType s =
                    io::readPrimitiveType<QualityType>(file, p.type, end);
                hasBeenRead = true;
                // in case the loaded polygon has been triangulated in the last
                // n triangles of mesh
                for (uint ff = f.index(); ff < mesh.faceCount(); ++ff) {
                    mesh.face(ff).quality() = s;
                }
            }
        }
    }
    else if (p.name == ply::unknown) {
        if constexpr (HasFaceCustomComponents<MeshType>) {
            if (mesh.hasFaceCustomComponent(p.unknownPropertyName)) {
                io::readCustomComponent(
                    file, f, p.unknownPropertyName, p.type, end);
                hasBeenRead = true;
            }
        }
    }
    // if nothing has been read, it means that there is some data we don't know
    // we still need to read and discard what we read
    if (!hasBeenRead) {
        if (p.list) {
            uint s = io::readPrimitiveType<uint>(file, p.listSizeType, end);
            for (uint i = 0; i < s; ++i)
                io::readPrimitiveType<int>(file, p.type, end);
        }
        else {
            io::readPrimitiveType<int>(file, p.type, end);
        }
    }
}

template<FaceConcept FaceType, MeshConcept MeshType>
void readPlyFaceTxt(
    std::istream&                 file,
    FaceType&                     f,
    MeshType&                     mesh,
    MeshInfo&                     loadedInfo,
    const std::list<PlyProperty>& faceProperties,
    bool                          vcgGenerated = false)
{
    Tokenizer           spaceTokenizer = readAndTokenizeNextNonEmptyLine(file);
    Tokenizer::iterator token          = spaceTokenizer.begin();
    std::vector<IndexType<MeshType>> vids;
    for (const PlyProperty& p : faceProperties) {
        if (token == spaceTokenizer.end()) {
            throw MalformedFileException("Unexpected end of line.");
        }
        readPlyFaceProperty(token, mesh, f, p, vids, loadedInfo, vcgGenerated);
    }
}

template<FaceConcept FaceType, MeshConcept MeshType>
void readPlyFaceBin(
    std::istream&                 file,
    FaceType&                     f,
    MeshType&                     mesh,
    MeshInfo&                     loadedInfo,
    const std::list<PlyProperty>& faceProperties,
    std::endian                   end,
    bool                          vcgGenerated = false)
{
    std::vector<IndexType<MeshType>> vids;
    for (const PlyProperty& p : faceProperties) {
        readPlyFaceProperty(
            file, mesh, f, p, vids, loadedInfo, vcgGenerated, end);
    }
}

template<FaceMeshConcept MeshType>
void writePlyFaces(
    std::ostream&    file,
    const PlyHeader& header,
    const MeshType&  mesh)
{
    using IndexType = IndexType<MeshType>;

    FileType format;
    if (header.format() == ply::ASCII) {
        format.isBinary = false;
    }
    else if (header.format() == ply::BINARY_BIG_ENDIAN) {
        format.endian = std::endian::big;
    }

    // indices of vertices that do not consider deleted vertices
    std::vector<IndexType> vIndices = mesh.vertexCompactIndices();

    for (const auto& f : mesh.faces()) {
        for (const PlyProperty& p : header.faceProperties()) {
            bool hasBeenWritten = false;
            if (p.name == ply::vertex_indices) {
                detail::writePlyFaceIndices(file, p, mesh, vIndices, f, format);
                hasBeenWritten = true;
            }
            else if (p.name == ply::bit_flags) {
                io::writeProperty(file, f.underlyingBitFlags(), p.type, format);
                hasBeenWritten = true;
            }
            else if (p.name >= ply::nx && p.name <= ply::nz) {
                if constexpr (HasFaceNormal<MeshType>) {
                    io::writeProperty(
                        file, f.normal()[p.name - ply::nx], p.type, format);
                    hasBeenWritten = true;
                }
            }
            else if (p.name >= ply::red && p.name <= ply::alpha) {
                if constexpr (HasFaceColor<MeshType>) {
                    io::writeProperty(
                        file, f.color()[p.name - ply::red], p.type, format);
                    hasBeenWritten = true;
                }
            }
            else if (p.name == ply::quality) {
                if constexpr (HasFaceQuality<MeshType>) {
                    io::writeProperty(file, f.quality(), p.type, format);
                    hasBeenWritten = true;
                }
            }
            else if (p.name == ply::texcoord) {
                if constexpr (HasFaceWedgeTexCoords<MeshType>) {
                    io::writeProperty(
                        file, f.vertexCount() * 2, p.listSizeType, format);
                    for (const auto& tc : f.wedges().texCoords()) {
                        io::writeProperty(file, tc.u(), p.type, format);
                        io::writeProperty(file, tc.v(), p.type, format);
                    }
                    hasBeenWritten = true;
                }
            }
            else if (p.name == ply::material_index) {
                if constexpr (HasFaceMaterialIndex<MeshType>) {
                    io::writeProperty(file, f.materialIndex(), p.type, format);
                    hasBeenWritten = true;
                }
            }
            else if (p.name == ply::unknown) {
                if constexpr (HasFaceCustomComponents<MeshType>) {
                    if (mesh.hasFaceCustomComponent(p.unknownPropertyName)) {
                        io::writeCustomComponent(
                            file, f, p.unknownPropertyName, p.type, format);
                        hasBeenWritten = true;
                    }
                }
            }
            if (!hasBeenWritten) {
                // be sure to write something if the header declares some
                // property that is not in the mesh
                io::writeProperty(file, 0, p.type, format);
            }
        }
        if (!format.isBinary)
            file << std::endl;
    }
}

template<FaceMeshConcept MeshType, LoggerConcept LogType>
void readPlyFaces(
    std::istream&    file,
    const PlyHeader& header,
    MeshType&        mesh,
    MeshInfo&        loadedInfo,
    LogType&         log)
{
    using FaceType = FaceType<MeshType>;
    mesh.reserveFaces(header.faceCount());

    log.startProgress("Reading faces", header.faceCount());

    for (uint fid = 0; fid < header.faceCount(); ++fid) {
        uint     ffid = mesh.addFace();
        FaceType f    = mesh.face(ffid);
        if (header.format() == ply::ASCII) {
            detail::readPlyFaceTxt(
                file,
                f,
                mesh,
                loadedInfo,
                header.faceProperties(),
                header.isVcgGenerated());
        }
        else {
            std::endian end = header.format() == ply::BINARY_BIG_ENDIAN ?
                                  std::endian::big :
                                  std::endian::little;
            detail::readPlyFaceBin(
                file,
                f,
                mesh,
                loadedInfo,
                header.faceProperties(),
                end,
                header.isVcgGenerated());
        }

        log.progress(fid);
    }

    log.endProgress();
}

